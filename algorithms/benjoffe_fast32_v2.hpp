#ifndef EAF_ALGORITHMS_BENJOFFE_FAST32_V2_H
#define EAF_ALGORITHMS_BENJOFFE_FAST32_V2_H

#include "eaf/date.hpp"

#include <stdint.h>

// Apple Silicon benefits from 64-bit comparison/select
#if defined(__APPLE__) && defined(__aarch64__)
#define CMPTYPE uint64_t
#else
#define CMPTYPE uint32_t
#endif

struct benjoffe_fast32_v2 {

  // Very fast 32-bit algorithm.
  // Not quite as fast as the 64-bit variant, but close.
  //
  // Julian Map technique explained in:
  // [1] https://www.benjoffe.com/fast-date
  //
  // Backwards-counting technique explained in:
  // [3] https://www.benjoffe.com/fast-date-64
  // 
  // Based on the 64-bit algorithm, but using smaller constants throughout,
  // avoiding umulh, and allow compiler more options on how to optimise,
  // including lea in more places.
  //
  // A new technique is used to reverse the year-count to the forward direction.
  // This needs to occur before the year-modulo-bitshift step:
  //   ((yrs & 3) * YRS_CYCLE)
  // Previously a subtraction was used, but this is right in the critical path.
  // This has been replaced with signed multiplication (YRS_MUL is negative)
  // This allows the `Y_SHIFT` to be moved to the end of the algorithm, where
  // it can sit in the shadow of prior steps.
  //
  // Three range options are presented.
  // Note that the wider options exceed 25% of the 32-bit input range, which is
  // unusual, almost all other 32-bit algorithms are less than 25% coverage.

  // Range Option (A)
  // Byte aligned range, uses smallest constants.
  // Gives good performance on both ARM and x86
  // These give a modest, but still useful range:
  // -284,449-07-13 to +284,449-01-30
  static int32_t constexpr SCALE = 8;
  static uint32_t constexpr ERAS = 4331;

  // Range Option (B)
  // x86 optimised (due to 16-bit shift for month calc) 
  // Accurate over range:
  // -1,587,925-07-04 to +1,587,745-02-19
  // Coverage: 1159889516 / 2^32 = 27.00578226%
  // static int32_t constexpr SCALE = 16;
  // static uint32_t constexpr ERAS = 3991;

  // Range Option (C)
  // ARM optimised (due to keeping many consts below 2^16)
  // Accurate within range:
  // -1,529,309-07-29 to +1,529,013-01-30
  // Coverage: 1117028995 / 2^32 = 26.00785799%
  // static int32_t constexpr SCALE = 12;
  // static uint32_t constexpr ERAS = 4022;

  // Rata Die shift:
  static uint32_t constexpr D_SHIFT = 146097 * ERAS - 719469;
  // Year shift:
  static uint32_t constexpr Y_SHIFT = 400 * ERAS;

  static uint32_t constexpr MSIZE = 1 << SCALE;
  static uint32_t constexpr YRS_CYCLE = MSIZE / 32 / 4;

  // Constants below are commented with their calculated value
  // for the case where `SCALE = 8`:
  static uint32_t constexpr CEN_MUL = uint32_t((1ull << 47) / 36524.25);       // 3853261555
  static int32_t constexpr YRS_MUL = -int32_t((1ull << 37) / 365.25 + 1);      // -376287347
  static uint32_t constexpr YPT_MUL = uint32_t((MSIZE) * 365.25 / 30.6 + 1);   // 3056
  static uint32_t constexpr DAY_MUL = uint32_t(((1ull << 32) * 30.6) / MSIZE); // 513382809
  static uint32_t constexpr CUTOFF = uint32_t(((10ll) << 32) * 30.6 / 365.25); // 3598247755
  static int32_t constexpr SHIFT_1 = -int32_t(590680ull * MSIZE / 65536);      // -2307
  static int32_t constexpr SHIFT_0 = SHIFT_1 + int32_t(12 * MSIZE);            // 765
  
  static inline
  date32_t to_date(int32_t dayNumber) {

    // 1. Adjust for 100/400 leap year rule.
    // Reverse day count technique explained in article [3]
    CMPTYPE const rev = D_SHIFT - dayNumber;
    CMPTYPE const cen = CMPTYPE(rev * uint64_t(CEN_MUL) >> 47);
    uint32_t const jul = rev - cen / 4 + cen;

    int64_t const num = jul * (int64_t(YRS_MUL)) >> 5;
    uint32_t const yrs = uint32_t(num >> 32);
    uint32_t const low = uint32_t(num);

    CMPTYPE const ypt = CMPTYPE(low * uint64_t(YPT_MUL) >> 32);

    CMPTYPE const bump = CMPTYPE(ypt) > 10 * MSIZE;
    CMPTYPE const shift = bump ? SHIFT_1 : SHIFT_0;
    CMPTYPE const m_num = (yrs & 3) * YRS_CYCLE + shift + ypt;
    
    uint32_t const month = m_num / MSIZE;
    uint32_t day = uint32_t((m_num % MSIZE) * uint64_t(DAY_MUL) >> 32) + 1;
    int32_t const year = int32_t(Y_SHIFT + yrs + bump);

    return { year, month, day };
  }

  // Fast overflow-safe inverse function.
  // Accurate over the full signed 32-bit output range.
  static inline
  int32_t to_rata_die(int32_t year, uint32_t month, uint32_t day) {

    uint32_t const bump = month <= 2;
    uint32_t const yrs = uint32_t(year + 5880000) - bump;
    uint32_t const cen = yrs / 100;
    int32_t const shift = bump ? 8829 : -2919;

    // Similar to Neri-Scheinder but slightly slower to avoid early overflow:
    uint32_t const year_days = yrs * 365 + yrs / 4 - cen + cen / 4;
    uint32_t const month_days = uint32_t(979 * int32_t(month) + shift) / 32;

    return int32_t(year_days + month_days + day - 2148345369u);
  }


}; // struct benjoffe_fast32_v2

#undef CMPTYPE

#endif // EAF_ALGORITHMS_BENJOFFE_FAST32_V2_H
