#ifndef EAF_ALGORITHMS_BENJOFFE_FAST64_V2_H
#define EAF_ALGORITHMS_BENJOFFE_FAST64_V2_H

#include "eaf/date.hpp"
#include "algorithms/_portable_int128.hpp"
#include "algorithms/_portable_uint128.hpp"

#include <stdint.h>

struct benjoffe_fast64_v2 {

  // Very fast 64-bit date algorithm - improved!
  // The following blog post URL will house the full explanation:
  // https://www.benjoffe.com/fast-date-refined
  //
  // In short, it's about 3% faster on Apple Silicon, but MUCH faster
  // on x64 with LLVM compiler (previous version optimised for x64 MSVC,
  // but gave poor results with other x64 compilers).
  //
  // Replaces backwards counting technique with a negative shift bias
  // and _signed_ 64x64 -> 128 bit results.
  //
  // Also a new "BIAS" variable is introduced to facilitate reducing
  // the month divisor down to only 256, which is optimal for both
  // ARM and x64, reducing the variation between the two target platforms.
  //
  // This version also can be easily adapted to a 32-bit version,
  // just replace num with: jul * 3853261555 >> 5;
  // This will be detailed in a future commit / blog post.
  //
  // This time, instead of just adjusting "ERAS" we must also adjust
  // "BIAS" accordingly. The below table shows various ERAS and matching
  // BIAS in order to achieve varying ranges. In general, smaller ranges
  // have some sma;l; performance benefits over wider ranges on some or
  // all platforms.  

  // Note: when using 

  /*
  +-------------------------+------------+-----------+------------------------+-----------------------+
  | Variant                 |    ERAS    |   BIAS    |        Min Date        |        Max Date       |
  +-------------------------+------------+-----------+------------------------+-----------------------+
  | 64-bit UNSIGNED D_SHIFT | 7453743012 |         5 | -489,539,574,661-07-13 | 489,539,578,745-01-30 | 
  | 48-bit UNSIGNED D_SHIFT | 1926630782 |        17 | -131,937,380,285-07-13 | 122,657,084,925-01-30 | 
  | 32-bit UNSIGNED D_SHIFT |      29402 |   1069052 |       -1,931,037-07-13 |       1,931,037-01-30 | 
  | 32-bit D_SHIFT          |      14703 |   2137813 |         -965,649-07-13 |         965,653-01-30 | 
  | 16-bit Y_SHIFT          |        163 | 192855448 |          -10,701-07-13 |          10,713-01-30 | 
  +-------------------------+------------+-----------+------------------------+------------------------
  */

  // Selected version for benchmarking is the 32-bit D_SHIFT
  // as it has a comparable range to Boost / Neri Schneider etc.
  // Range: -965,649-07-13 to 965,653-01-30.
  // (16.4% of 32-bit range).

  // To verify range, edit the ERAS and BIAS below, and run:
  // cmake --build build --parallel && build/bin/rangetest_fast_32

  static uint64_t constexpr ERAS = 14703;
  static uint64_t constexpr BIAS = 2137813;

  static int64_t constexpr D_SHIFT = -146097l * ERAS + 719469l;
  static uint64_t constexpr Y_SHIFT = 400 * ERAS;

  static uint64_t constexpr CEN_MUL = 505054698555331ull;          // floor(2^64 / 36524.25)
  static uint64_t constexpr YRS_MUL = 50504432782230120ull + BIAS; // floor(2^64 / 365.25) + BIAS
  static uint64_t constexpr DAY_MUL = 2204962377560594841ull;      // floor(2^64 * 30.6 / 256)
  static uint64_t constexpr YPT_MUL = 3056ull;                     // ceil(365.25 / 30.6 * 256)
    
  // Use different variable sizes in some places for optimal codegen.
  // Does not change any math / overflow characteristics.
  #if defined(__aarch64__) || defined(_M_ARM64)
    using uintXX_t = uint64_t;
  #else
    using uintXX_t = uint32_t;
  #endif

  static inline
  date32_t to_date(int32_t dayNumber) {
    
    int64_t const rev = dayNumber + D_SHIFT;
    int64_t const cen = CEN_MUL * int128_t(rev) >> 64;
    int64_t const jul = rev + cen - (cen >> 2);

    int128_t const num = int128_t(jul) * YRS_MUL;
    uintXX_t const yrs = uintXX_t(num >> 64); // Change to uint64_t if using wide range
    uint64_t const low = uint64_t(num);
    uintXX_t const ypt = uintXX_t(low * uint128_t(YPT_MUL) >> 64);
  
    uintXX_t const bump = ypt > 10u * 256;
    int32_t const shift = bump ? 765 - 12 * 256 : 765;

    uint32_t const N = (yrs & 3) * 2 + ypt + shift;
    uint32_t const month = N / 256;
    uint32_t const day = uint32_t(uint64_t((N % 256) * uint128_t(DAY_MUL) >> 64) + 1);
    int32_t const year = int32_t(yrs + bump + Y_SHIFT);

    return date32_t{year, month, day};
  }

  // Fast overflow-safe inverse function.
  // Accurate over the full signed 32-bit output range.
  static inline
  int32_t to_rata_die(int32_t year, uint32_t month, uint32_t day) {

    uint32_t const bump = month <= 2;
    uint32_t const yrs = uint32_t(year + 5880000) - bump;
    uint32_t const cen = yrs / 100;
    int32_t const shift = bump ? 8829 : -2919;

    // Similar to Neri-Scheinder but slightly slower to avoid early overflow:
    uint32_t const year_days = yrs * 365 + yrs / 4 - cen + cen / 4;
    uint32_t const month_days = (979 * int32_t(month) + shift) / 32;
    
    return year_days + month_days + day - 2148345369u;
  }

}; // struct benjoffe_fast64_v2

#endif // EAF_ALGORITHMS_BENJOFFE_FAST64_V2_H
